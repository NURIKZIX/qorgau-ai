def scroll_page():
    scroll = QScrollArea()
    scroll.setWidgetResizable(True)
    page = QWidget()
    page.setObjectName("content")
    box = QVBoxLayout(page)
    box.setContentsMargins(0, 0, 3, 0)
    box.setSpacing(16)
    scroll.setWidget(page)
    return scroll, box


def metric_strip(entries):
    layout = QHBoxLayout()
    layout.setSpacing(12)
    values, captions = [], []
    for index, (title, value, caption) in enumerate(entries):
        widget, box = card()
        box.setContentsMargins(18, 14, 18, 14)
        box.setSpacing(4)
        box.addWidget(label(title, "eyebrow"))
        metric = label(value, "metricAccent" if index == 0 else "metricValue")
        text = label(caption, "muted")
        box.addWidget(metric)
        box.addWidget(text)
        values.append(metric)
        captions.append(text)
        layout.addWidget(widget, 1)
    return layout, values, captions


