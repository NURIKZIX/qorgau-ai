def settings_page(w):
    scroll, layout = scroll_page()
    presets, box = card("Выберите профиль наблюдения")
    box.addWidget(label("Профиль меняет задержки и угол головы. Номер камеры, уверенность моделей и сохранение кадров остаются вашими.", "muted"))
    row = QHBoxLayout()
    w.preset_buttons = []
    for key, (title, _) in PRESETS.items():
        control = button(title, lambda checked=False, p=key: w.apply_preset(p))
        w.preset_buttons.append(control)
        row.addWidget(control)
    box.addLayout(row)
    w.preset_hint = label("Изменения вступят в силу после сохранения и следующего подключения.", "muted")
    box.addWidget(w.preset_hint)
    layout.addWidget(presets)
    groups = QHBoxLayout()
    detection, detection_box = card("Камера и детекция")
    timing, timing_box = card("Когда регистрировать событие")
    detection_form, timing_form = QFormLayout(), QFormLayout()
    for form in (detection_form, timing_form):
        form.setSpacing(14)
    w.setting_fields = {}
    options = [("camera_index", "Номер камеры", 0, 9, 1),
        ("confidence", "Уверенность: человек", .1, .95, .05), ("phone_confidence", "Уверенность: телефон", .1, .95, .05),
        ("head_angle", "Поворот головы, °", 10, 80, 5), ("phone_seconds", "Телефон — задержка, с", .5, 60, .5),
        ("multiple_seconds", "Несколько людей — задержка, с", .5, 60, .5), ("absence_seconds", "Отсутствие — задержка, с", .5, 60, .5),
        ("head_seconds", "Поворот головы — задержка, с", .5, 60, .5), ("window_seconds", "Выход из окна — задержка, с", 0, 60, .5)]
    for key, caption, minimum, maximum, step in options:
        field = QSpinBox() if key == "camera_index" else QDoubleSpinBox()
        field.setRange(minimum, maximum)
        field.setSingleStep(step)
        field.setValue(getattr(w.settings, key))
        field.setAccessibleName(caption)
        field.setMaximumWidth(140)
        w.setting_fields[key] = field
        form = timing_form if key.endswith("_seconds") else detection_form
        form.addRow(label(caption, "muted"), field)
    detection_box.addLayout(detection_form)
    detection_box.addWidget(label("Уверенность помогает отсеять слабые распознавания. Угол головы измеряет ориентацию лица, а не направление взгляда.", "muted"))
    detection_box.addStretch()
    timing_box.addLayout(timing_form)
    timing_box.addWidget(label("0 секунд для окон — без дополнительной задержки. Клавиши регистрируются сразу.", "muted"))
    groups.addWidget(detection, 1)
    groups.addWidget(timing, 1)
    layout.addLayout(groups)
    privacy, box = card("Данные под вашим контролем")
    w.evidence_check = QCheckBox("Сохранять один кадр визуального события")
    w.evidence_check.setChecked(w.settings.save_evidence)
    box.addWidget(w.evidence_check)
    box.addWidget(label("По умолчанию кадры выключены. Текст, экран и буфер обмена не собираются. Данные остаются на этом компьютере.", "muted"))
    row = QHBoxLayout()
    w.save_settings_button = button("Сохранить настройки", w.save_settings, "primary")
    row.addWidget(w.save_settings_button)
    row.addStretch()
    row.addWidget(button("Открыть папку данных", w.open_data_folder))
    box.addLayout(row)
    layout.addWidget(privacy)
    layout.addStretch()
    return scroll
